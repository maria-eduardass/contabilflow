CREATE TABLE avaliacoes (
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT UNSIGNED NULL,
  perfil     ENUM('admin','contador') NOT NULL,
  q1 TINYINT UNSIGNED NOT NULL,
  q2 TINYINT UNSIGNED NOT NULL,
  q3 TINYINT UNSIGNED NOT NULL,
  q4 TINYINT UNSIGNED NOT NULL,
  q5 TINYINT UNSIGNED NOT NULL,
  nps        TINYINT UNSIGNED NOT NULL,
  comentario VARCHAR(1000) NULL,
  criado_em  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_avaliacoes_perfil (perfil),
  CONSTRAINT fk_avaliacoes_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuarios(id) ON DELETE SET NULL,
  CONSTRAINT chk_avaliacoes_q CHECK (q1 BETWEEN 1 AND 5 AND q2 BETWEEN 1 AND 5
    AND q3 BETWEEN 1 AND 5 AND q4 BETWEEN 1 AND 5 AND q5 BETWEEN 1 AND 5),
  CONSTRAINT chk_avaliacoes_nps CHECK (nps BETWEEN 0 AND 10)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
